    pg.wait_for_function("document.body.dataset.tela==='app'")
    assert pg.locator('#menu a[data-rota="s/apoio"]').count()==1; ok('Apoio às Avaliações aparece no menu')
    pg.goto(B+'#/s/apoio'); pg.wait_for_timeout(2500)
    f=[x for x in pg.frames if 'modulos/apoio' in x.url][0]; f.wait_for_selector('.lembrete')
