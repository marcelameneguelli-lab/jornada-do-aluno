    f.click('#btn-novo'); f.wait_for_selector('#form-apoio')
    assert f.locator('[name=diagnostico],[name=condicao],[name=cid]').count()==0; ok('o formulário não tem campo de diagnóstico')
    f.fill('[name=matricula]','202301000102'); f.fill('[name=aluno]','Engaja Exemplo 3'); f.fill('[name=curso]','Direito')
