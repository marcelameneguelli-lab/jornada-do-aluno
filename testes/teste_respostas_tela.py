import json
from playwright.sync_api import sync_playwright
prov=json.load(open('/tmp/prov.json')); B='http://localhost:8765/'; erros=[]; n=0
def ok(m):
    global n; n+=1; print('ok ',m)
with sync_playwright() as p:
    br=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    ctx=br.new_context(viewport={'width':1366,'height':900}); pg=ctx.new_page()
    pg.on('pageerror', lambda e: erros.append('PAGEERR '+str(e)))
    pg.on('console', lambda m: erros.append(m.text) if m.type=='error' and 'ERR_FAILED' not in m.text and 'fonts' not in m.text else None)
    pg.add_init_script("try{localStorage.setItem('jornada_gas_url','http://localhost:8765/exec')}catch(e){}")
    pg.goto(B); pg.fill('#login-email','angelica@estacio.br'); pg.fill('#login-senha',prov['atend']); pg.click('#btn-entrar')
    pg.wait_for_selector('#form-troca:not([hidden])'); pg.fill('#troca-atual',prov['atend']); pg.fill('#troca-nova','Atend2026b'); pg.fill('#troca-conf','Atend2026b'); pg.click('#form-troca button.primario')
    pg.wait_for_function("document.body.dataset.tela==='app'")
    assert 'Central de Respostas' in pg.inner_text('#menu'); ok('menu: Central de Respostas em Ferramentas da equipe')
    pg.click('a[href="#/f/respostas"]'); pg.wait_for_timeout(2500)
    f=[x for x in pg.frames if 'modulos/respostas' in x.url][0]; f.wait_for_selector('.card', timeout=15000)
    tot=f.inner_text('#stat-total'); assert int(tot)>=50, tot; ok(f'{tot} modelos padrão carregados')
    f.fill('#busca','meu estágio está parado, falta assinar o contrato'); f.wait_for_timeout(300)
    assert 'Modelos sugeridos' in f.inner_text('#titulo-lista') and 'estágio' in f.inner_text('.card').lower(); ok('busca pelo texto do aluno sugere modelos de estágio')
    f.click('#limpar-busca'); f.click('[data-cat="atendimento"]'); f.wait_for_timeout(200)
    f.click('.card[data-id="at_saudacao"] .card-usar'); f.wait_for_selector('#fundo-editor.aberto')
    nm=f.input_value('[data-var="atendente"]'); assert nm.startswith('Ang'), nm; assert 'Sou '+nm in f.inner_text('#preview-texto'); ok('{{atendente}} já vem com o nome de quem está logado')
    pg.screenshot(path='/home/claude/testes/tela_respostas.png')
    f.evaluate("navigator.clipboard.writeText=()=>Promise.resolve()"); f.click('#btn-copiar'); f.wait_for_timeout(1500)
    f.click('#fechar-editor'); f.wait_for_timeout(300)
    f.click('#btn-novo-modelo'); f.select_option('#novo-categoria','financeiro'); f.fill('#novo-titulo','Lembrete de vencimento'); f.fill('#novo-tags','vencimento, boleto'); f.fill('#novo-texto','Olá, {{nome}}! Seu boleto vence amanhã.')
    f.click('#btn-salvar-modelo'); f.wait_for_timeout(1500)
    ctx2=br.new_context(viewport={'width':1366,'height':900}); p2=ctx2.new_page(); p2.add_init_script("try{localStorage.setItem('jornada_gas_url','http://localhost:8765/exec')}catch(e){}")
    p2.goto(B); p2.fill('#login-email','marques.marcela@estacio.br'); p2.fill('#login-senha',prov['admin']); p2.click('#btn-entrar')
    p2.wait_for_selector('#form-troca:not([hidden])'); p2.fill('#troca-atual',prov['admin']); p2.fill('#troca-nova','Admin2026b'); p2.fill('#troca-conf','Admin2026b'); p2.click('#form-troca button.primario')
    p2.wait_for_function("document.body.dataset.tela==='app'"); p2.goto(B+'#/f/respostas'); p2.wait_for_timeout(2500)
    f2=[x for x in p2.frames if 'modulos/respostas' in x.url][0]; f2.wait_for_selector('.card', timeout=15000)
    f2.fill('#busca','vencimento boleto'); f2.wait_for_timeout(300)
    assert 'Lembrete de vencimento' in f2.inner_text('#grade'); ok('modelo criado pela Angelica aparece para a Marcela')
    assert int(f2.inner_text('#stat-usos'))>=1; ok('envio registrado aparece na contagem da equipe')
    br.close()
print(n,'passos ok'); print('erros:', erros or 'nenhum')
